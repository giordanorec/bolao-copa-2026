export type Locale = "pt" | "en" | "es" | "fr";
export const LOCALES: Locale[] = ["pt", "en", "es", "fr"];
export const LOCALE_DEFAULT: Locale = "pt";

export const LOCALE_NOMES: Record<Locale, string> = {
  pt: "Português",
  en: "English",
  es: "Español",
  fr: "Français",
};

export const LOCALE_FLAGS: Record<Locale, string> = {
  pt: "🇧🇷",
  en: "🇺🇸",
  es: "🇪🇸",
  fr: "🇫🇷",
};

// Mapa país (ISO 3166-1 alpha-2) → locale default
const PAIS_PARA_LOCALE: Record<string, Locale> = {
  BR: "pt", PT: "pt", AO: "pt", MZ: "pt", CV: "pt", GW: "pt", TL: "pt",
  US: "en", GB: "en", AU: "en", NZ: "en", IE: "en", IN: "en", ZA: "en", SG: "en", PH: "en", NG: "en", KE: "en",
  CA: "en", // Canadá majoritário em
  ES: "es", MX: "es", AR: "es", CO: "es", CL: "es", PE: "es", VE: "es", UY: "es",
  PY: "es", BO: "es", EC: "es", CR: "es", GT: "es", HN: "es", PA: "es", DO: "es", CU: "es", NI: "es", SV: "es",
  FR: "fr", BE: "fr", CH: "fr", LU: "fr", MC: "fr", SN: "fr", CI: "fr", ML: "fr", BF: "fr", CM: "fr", MG: "fr",
};

export function localeDoPais(codigoPais: string | null | undefined): Locale {
  if (!codigoPais) return LOCALE_DEFAULT;
  return PAIS_PARA_LOCALE[codigoPais.toUpperCase()] ?? LOCALE_DEFAULT;
}

export function localeDoAcceptLanguage(header: string | null | undefined): Locale {
  if (!header) return LOCALE_DEFAULT;
  const primeiras = header
    .split(",")
    .map((p) => p.trim().split(";")[0].slice(0, 2).toLowerCase());
  for (const p of primeiras) {
    if ((LOCALES as string[]).includes(p)) return p as Locale;
  }
  return LOCALE_DEFAULT;
}

